def rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5)) + (255,)


def textura_ruido(img, ox, oy, base, motas, semilla, densidad=0.18):
    rnd = random.Random(semilla)
    for y in range(16):
        for x in range(16):
            img.putpixel((ox + x, oy + y), base)
    for y in range(16):
        for x in range(16):
            if rnd.random() < densidad:
                img.putpixel((ox + x, oy + y), rnd.choice(motas))


