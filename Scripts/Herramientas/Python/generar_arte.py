def casa():
    img = lienzo(48, 48)
    teja = rgb("#c4553a"); teja_o = rgb("#8f3426"); teja_c = rgb("#e0785a")
    pared = rgb("#f2ece0"); pared_o = rgb("#d3cbbb")
    madera = rgb("#3f7fbf"); madera_o = rgb("#2a5a8a")   # carpintería azul
    balcon = rgb("#2f9e6a"); balcon_o = rgb("#1f6e48")   # balcón verde
    k = P['k']
    # tejado (filas 2-17)
    for y in range(2, 18):
        margen = max(0, 9 - (y - 2))
        for x in range(1 + margen // 2, 47 - margen // 2):
            c = teja if (y % 3) else teja_o
            if (x + (y // 3) * 2) % 6 == 0:
                c = teja_c
            img.putpixel((x, y), c)
    for x in range(0, 48):
        img.putpixel((x, 17), teja_o)
        img.putpixel((x, 18), k)
    # contorno tejado
    for y in range(2, 18):
        margen = max(0, 9 - (y - 2))
        img.putpixel((margen // 2, y), k)
        img.putpixel((47 - margen // 2, y), k)
    for x in range(5, 43):
        img.putpixel((x, 1), k)
    # paredes (19-45)
    for y in range(19, 46):
        for x in range(3, 45):
            img.putpixel((x, y), pared if x % 11 else pared_o)
        img.putpixel((2, y), k); img.putpixel((45, y), k)
    for x in range(2, 46):
        img.putpixel((x, 46), k)
        img.putpixel((x, 45), pared_o)
    # zócalo
    for y in range(41, 46):
        for x in range(3, 45):
            img.putpixel((x, y), balcon_o if y == 41 else balcon)
    # puerta
    for y in range(29, 46):
        for x in range(20, 28):
            c = madera if (x - 20) % 4 else madera_o
            if x in (20, 27) or y == 29:
                c = k
            img.putpixel((x, y), c)
    img.putpixel((25, 38), rgb("#ffe36e"))
    # ventanas con postigos
    for wx in (7, 34):
        for y in range(23, 33):
            for x in range(wx, wx + 8):
                c = rgb("#203048") if (x not in (wx, wx + 7) and y not in (23, 32)) else k
                if wx + 1 <= x <= wx + 6 and 24 <= y <= 31 and (x == wx + 3 or y == 27):
                    c = madera
                img.putpixel((x, y), c)
        # postigos
        for y in range(23, 33):
            img.putpixel((wx - 2, y), madera); img.putpixel((wx - 1, y), madera_o)
            img.putpixel((wx + 8, y), madera_o); img.putpixel((wx + 9, y), madera)
        # baranda del balcón
        for x in range(wx - 2, wx + 10):
            img.putpixel((x, 33), balcon_o)
            img.putpixel((x, 36), balcon_o)
            if x % 2 == 0:
                img.putpixel((x, 34), balcon); img.putpixel((x, 35), balcon)
    # sombra en el suelo
    for x in range(4, 44):
        img.putpixel((x, 47), (0, 0, 0, 70))
    img.save(os.path.join(SALIDA, "casa.png"))


