def lienzo(an, al):
    return Image.new("RGBA", (an, al), (0, 0, 0, 0))


def pintar(img, mapa, ox=0, oy=0, paleta=P, espejo=False):
    """Dibuja un mapa de caracteres en la imagen."""
    filas = [f for f in mapa.strip("\n").split("\n")]
    for y, fila in enumerate(filas):
        if espejo:
            fila = fila[::-1]
        for x, ch in enumerate(fila):
            col = paleta.get(ch)
            px, py = ox + x, oy + y
            if col is not None and 0 <= px < img.width and 0 <= py < img.height:
                img.putpixel((px, py), col)


def verificar(nombre, mapa, an, al):
    filas = mapa.strip("\n").split("\n")
    assert len(filas) == al, f"{nombre}: {len(filas)} filas (esperaba {al})"
    for i, f in enumerate(filas):
        assert len(f) == an, f"{nombre} fila {i}: ancho {len(f)} (esperaba {an}) -> '{f}'"


