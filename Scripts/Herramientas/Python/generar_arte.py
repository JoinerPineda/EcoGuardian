def cuadro_jugador(cabeza, torso, piernas, salto):
    img = lienzo(16, 16)
    # salto = 1 hace que el cuerpo suba un pixel al caminar
    pintar(img, cabeza, 0, -1 - salto)
    pintar(img, torso, 0, 10 - salto)
    pintar(img, piernas, 0, 13)
    return img


def hoja_jugador():
    for n, m, a, al in [("cabeza_abajo", CABEZA_ABAJO, 16, 11), ("cabeza_arriba", CABEZA_ARRIBA, 16, 11),
                        ("cabeza_der", CABEZA_DERECHA, 16, 11), ("torso_ab", TORSO_ABAJO, 16, 4),
                        ("torso_ar", TORSO_ARRIBA, 16, 4), ("torso_der", TORSO_DERECHA, 16, 4)]:
        verificar(n, m, a, al)
    for i, pz in enumerate(PIERNAS_FRENTE + PIERNAS_LADO):
        verificar(f"piernas{i}", pz, 16, 3)

    hoja = lienzo(64, 64)
    filas = [
        (CABEZA_ABAJO, TORSO_ABAJO, PIERNAS_FRENTE, False),   # fila 0: abajo
        (CABEZA_ARRIBA, TORSO_ARRIBA, PIERNAS_FRENTE, False), # fila 1: arriba
        (CABEZA_DERECHA, TORSO_DERECHA, PIERNAS_LADO, True),  # fila 2: izquierda (espejo)
        (CABEZA_DERECHA, TORSO_DERECHA, PIERNAS_LADO, False), # fila 3: derecha
    ]
    for fila, (cab, tor, pier, espejo) in enumerate(filas):
        for c in range(4):
            salto = 1 if c in (1, 3) else 0
            cuadro = cuadro_jugador(cab, tor, pier[c], salto)
            if espejo:
                cuadro = cuadro.transpose(Image.FLIP_LEFT_RIGHT)
            hoja.paste(cuadro, (c * 16, fila * 16), cuadro)
    hoja.save(os.path.join(SALIDA, "jugador.png"))


